const line = (notes: number[], step = 0.8) =>
  notes.map((midi, i) => ({ midi, beat: i * step, duration: step * 0.85 }));
const chords = (sets: number[][]) =>
  sets.flatMap((notes, i) =>
    notes.map((midi) => ({ midi, beat: i * 2, duration: 1.7 })),
  );
